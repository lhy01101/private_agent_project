# 示例编写原则（agg = max 时）：
#   - 每条 example 覆盖一个「独特语义邻域」，允许多种措辞表达同一意图
#     （max 取最近邻，多一种措辞 = 多覆盖一片邻域，对簇内召回有利）；
#     但杜绝逐字重复——max 只取最大值，完全相同的 example 是纯浪费预算。
#     → 因此「10 条各不相同的表达」依然优于「5 条同义改写」，
#        理由不是"防权重集中"（那是 mean 的顾虑），而是"覆盖面更广"。
#   - 「覆盖面 > 示例总数」：max 无均值兜底，长尾 query 落入未覆盖区域即得 0 分，
#     故应优先覆盖不同子场景/邻域，而非在同一说法上堆条数。
#   - 负例用「难负例」：即「看起来很像本路由、但其实属于别的路由」的句子，
#     这正是下方每个路由 negative_examples 的主要来源（= 其他路由的正例）。
#     max 下难负例效率极高：一条命中即可强力拉回分数。
